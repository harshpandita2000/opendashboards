import type { Metadata } from "next";
import { Suspense } from "react";

import { PageHeader, SectionLabel } from "@/components/page-header";
import {
  CreateOrgForm,
  InvitePanel,
  McpPolicy,
  MembersList,
  ModelProviders,
  OrgGeneralForm,
  OrgSwitcher,
} from "@/components/settings/settings-forms";
import { Skeleton } from "@/components/ui/skeleton";
import { getConnectionService } from "@/lib/connections";
import { getModelProviderService } from "@/lib/models";
import { getOrgService } from "@/lib/orgs";
import { requireOrg } from "@/lib/orgs/current";
import { assignableRoles, hasRole } from "@/lib/orgs/roles";

export const metadata: Metadata = { title: "Settings" };

export default function SettingsPage() {
  return (
    <div className="mx-auto w-full max-w-3xl px-6 py-12">
      <PageHeader
        title="Organisation settings"
        description="Who's in your organisation, the model your Build agent uses, and which MCP servers and tools members may connect."
      />
      <Suspense fallback={<Skeleton className="h-64 w-full" />}>
        <Settings />
      </Suspense>
    </div>
  );
}

async function Settings() {
  const { org, role, user, memberships } = await requireOrg();
  const actor = { orgId: org.id, userId: user.id, role };
  const admin = hasRole(role, "admin");
  const orgs = getOrgService();
  const [members, invites, providers, servers] = await Promise.all([
    orgs.members(actor),
    admin ? orgs.invites(actor) : Promise.resolve([]),
    admin ? getModelProviderService().list(actor) : Promise.resolve([]),
    admin ? getConnectionService().mcpPolicies({ orgId: org.id, userId: user.id, role }) : Promise.resolve([]),
  ]);

  return (
    <div className="space-y-10">
      <section aria-labelledby="org" className="space-y-4">
        <SectionLabel id="org">Organisation</SectionLabel>
        <OrgSwitcher current={org.id} orgs={memberships.map(({ id, name, role: r, personal }) => ({ id, name: personal ? `${name} (personal)` : name, role: r }))} />
        <OrgGeneralForm name={org.name} canEdit={admin} canDelete={role === "owner" && !org.personal} canLeave={role !== "owner"} />
        <CreateOrgForm />
      </section>

      <section aria-labelledby="members" className="space-y-4">
        <SectionLabel id="members">Members</SectionLabel>
        <p className="text-sm text-muted-foreground">
          Owners and admins manage members, models and policies. Members build apps and add connections. Viewers open dashboards, and run only
          the queries each dashboard was built with.
        </p>
        <MembersList
          members={members.map(({ userId, email, role: r }) => ({ userId, email, role: r }))}
          me={user.id}
          canManage={admin}
          roles={assignableRoles(role)}
        />
        {admin && !org.personal && (
          <InvitePanel
            invites={invites.map(({ id, email, role: r, expiresAt }) => ({ id, email, role: r, expiresAt: expiresAt.toISOString() }))}
            roles={assignableRoles(role)}
          />
        )}
        {admin && org.personal && <p className="text-sm text-muted-foreground">Create a team organisation to invite people.</p>}
      </section>

      {admin && (
        <section aria-labelledby="models" className="space-y-4">
          <SectionLabel id="models">Models</SectionLabel>
          <p className="text-sm text-muted-foreground">
            The Build agent&apos;s chat runs on your organisation&apos;s own Azure OpenAI deployment when one is in use. Dashboards are still
            generated by OpenUI Cloud.
          </p>
          <ModelProviders
            providers={providers.map((provider) => ({
              id: provider.id,
              name: provider.name,
              endpoint: provider.config.endpoint,
              deployment: provider.config.deployment,
              apiVersion: provider.config.apiVersion,
              authMode: provider.config.authMode,
              credentialHint: provider.credentialHint,
              isDefault: provider.isDefault,
              status: provider.status,
              lastError: provider.lastError,
            }))}
          />
        </section>
      )}

      {admin && (
        <section aria-labelledby="mcp" className="space-y-4">
          <SectionLabel id="mcp">MCP servers</SectionLabel>
          <McpPolicy allowedHosts={org.settings.mcpAllowedHosts ?? null} servers={servers} />
        </section>
      )}
    </div>
  );
}
